/**
 * Normalizes district names by stripping spaces, special diacritics,
 * and mapping Bengali alternate spellings (e.g., য় vs য়, ড় vs ড়).
 */
export function normalizeGeoName(name: string): string {
  if (!name) return '';
  return name
    .trim()
    .toLowerCase()
    .replace(/[\s\-_']/g, '')
    .replace(/য়/g, 'য়')
    .replace(/ড়/g, 'ড়')
    .replace(/ঢ়/g, 'ঢ়')
    .replace(/ণ/g, 'ন');
}

/**
 * Finds upazilas for any district name (Bangla or English) across all divisions.
 */
export function getUpazilasForDistrict(districtName: string): string[] {
  if (!districtName) return [];
  const normalized = normalizeGeoName(districtName);

  for (const div of BANGLADESH_DIVISIONS) {
    for (const dist of div.districts) {
      if (
        normalizeGeoName(dist.nameBn) === normalized ||
        normalizeGeoName(dist.nameEn) === normalized
      ) {
        return [...dist.upazilas];
      }
    }
  }

  // Fallback: return common default list if not matched
  return ['সদর', 'পৌরসভা', 'উত্তর', 'দক্ষিণ'];
}

/**
 * Checks whether a district is in Dhaka Division for delivery fee calculation.
 */
export function isDhakaMetroDistrict(districtName: string): boolean {
  const normalized = normalizeGeoName(districtName);
  return normalized === 'ঢাকা' || normalized === 'dhaka';
}
